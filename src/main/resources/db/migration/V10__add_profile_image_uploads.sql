-- API-08 프로필 이미지 업로드 URL 발급. Tracks each presigned-URL issuance so API-06 can verify
-- a profileImageKey was actually issued to the linking user before trusting it.
CREATE TABLE profile_image_uploads (
    profile_image_upload_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    object_key VARCHAR(255) NOT NULL UNIQUE,
    content_type VARCHAR(20) NOT NULL,
    reported_file_size BIGINT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ISSUED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CHECK (reported_file_size BETWEEN 1 AND 5242880),
    CHECK (status IN ('ISSUED', 'LINKED'))
);

-- API-06 looks up "the ISSUED row for this user+key" on every profileImageKey link attempt.
CREATE INDEX idx_profile_image_uploads_user_status ON profile_image_uploads(user_id, status);
