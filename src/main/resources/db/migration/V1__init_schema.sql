-- HobbyTree v1.2 FINAL CANDIDATE / PostgreSQL 15+ / 18 tables
-- Fresh schema for empty DB. Not a migration for an existing populated database.
-- Core: original 14 tables. Added: saved_activities, experiences, experience_reservations, notification_subscriptions.
-- Deferred: chat, AI conversation persistence, internal payments, advertising master.
-- Payment policy: external merchant handles checkout; do NOT treat the in-app checkout mockup as implemented.
-- Capacity and tree growth require transaction-level locking in the application.
-- 18 tables; designed for fresh database, not an ALTER migration.
CREATE TABLE users (
                       user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       provider VARCHAR(20) NOT NULL CHECK (provider IN ('KAKAO','GOOGLE')),
                       provider_user_id VARCHAR(255) NOT NULL,
                       nickname VARCHAR(50), profile_image_key TEXT, age_range VARCHAR(20),
                       user_role VARCHAR(20) NOT NULL DEFAULT 'USER' CHECK (user_role IN ('USER','ADMIN')),
                       account_status VARCHAR(24) NOT NULL DEFAULT 'PENDING_ONBOARDING' CHECK (account_status IN ('PENDING_ONBOARDING','ACTIVE','WITHDRAWN','SUSPENDED')),
                       withdrawn_at TIMESTAMPTZ,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                       UNIQUE(provider,provider_user_id),
                       CHECK (
                           (account_status = 'WITHDRAWN' AND withdrawn_at IS NOT NULL)
                               OR
                           (account_status <> 'WITHDRAWN' AND withdrawn_at IS NULL)
                           )
);
CREATE TABLE user_preferences (
                                  preference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
                                  hobby_status VARCHAR(40), first_activity_budget INTEGER CHECK (first_activity_budget BETWEEN 0 AND 1000000),
                                  first_budget_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN' CHECK (first_budget_status IN ('SET','DECIDE_LATER','UNKNOWN')),
                                  monthly_budget INTEGER CHECK (monthly_budget BETWEEN 0 AND 3000000), session_minutes INTEGER CHECK (session_minutes BETWEEN 10 AND 480),
                                  weekly_frequency VARCHAR(40), preferred_environment VARCHAR(40), companion_preference VARCHAR(40),
                                  activity_selection_style VARCHAR(40), record_style VARCHAR(40),
                                  notification_frequency VARCHAR(30) NOT NULL DEFAULT 'NONE',
                                  preferred_hobbies JSONB NOT NULL DEFAULT '[]'::jsonb, goals JSONB NOT NULL DEFAULT '[]'::jsonb,
                                  owned_assets JSONB NOT NULL DEFAULT '[]'::jsonb, exclusions JSONB NOT NULL DEFAULT '[]'::jsonb,
                                  hobby_specific_answers JSONB NOT NULL DEFAULT '{}'::jsonb,
                                  custom_interest_text VARCHAR(200), additional_consideration TEXT,
                                  CHECK ((first_budget_status = 'SET' AND first_activity_budget IS NOT NULL) OR (first_budget_status <> 'SET' AND first_activity_budget IS NULL)),
                                  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE user_locations (
                                user_location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
                                region_sido VARCHAR(50) NOT NULL, region_sigungu VARCHAR(50) NOT NULL,
                                location_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (location_status IN ('ACTIVE','REVOKED')),
                                updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE location_consent_history (
                                          location_consent_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                          consent_action VARCHAR(20) NOT NULL CHECK (consent_action IN ('GRANTED','REVOKED')),
                                          terms_version VARCHAR(40) NOT NULL, changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE hobbies (
                         hobby_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         hobby_code VARCHAR(50) NOT NULL UNIQUE, hobby_name VARCHAR(100) NOT NULL,
                         description TEXT, activities_per_stage SMALLINT NOT NULL DEFAULT 3 CHECK (activities_per_stage > 0),
                         is_supported BOOLEAN NOT NULL DEFAULT TRUE,
                         created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE hobby_stages (
                              hobby_stage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              hobby_id BIGINT NOT NULL REFERENCES hobbies(hobby_id) ON DELETE CASCADE,
                              stage_number SMALLINT NOT NULL CHECK (stage_number BETWEEN 0 AND 5),
                              stage_name VARCHAR(100) NOT NULL, stage_description TEXT, tree_image_key TEXT,
                              UNIQUE(hobby_id,stage_number)
);
CREATE TABLE activities (
                            activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            hobby_stage_id BIGINT NOT NULL REFERENCES hobby_stages(hobby_stage_id),
                            activity_code VARCHAR(80) NOT NULL UNIQUE, activity_name VARCHAR(160) NOT NULL,
                            category VARCHAR(80), short_description VARCHAR(500), detailed_description TEXT,
                            expected_active_minutes INTEGER CHECK(expected_active_minutes >= 0),
                            expected_total_minutes INTEGER CHECK(expected_total_minutes >= 0),
                            estimated_cost_min INTEGER CHECK(estimated_cost_min >= 0),
                            estimated_cost_max INTEGER CHECK(estimated_cost_max >= 0),
                            difficulty VARCHAR(30), required_conditions JSONB, safety_notes TEXT,
                            review_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (review_status IN ('DRAFT','REVIEW','PUBLISHED','REJECTED')),
                            created_by_user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
                            reviewed_by_user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
                            reviewed_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                            CHECK(estimated_cost_max IS NULL OR estimated_cost_min IS NULL OR estimated_cost_max >= estimated_cost_min)
);
CREATE TABLE activity_steps (
                                activity_step_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                activity_id BIGINT NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
                                step_number SMALLINT NOT NULL CHECK(step_number > 0), instruction TEXT NOT NULL,
                                UNIQUE(activity_id,step_number)
);
CREATE TABLE activity_materials (
                                    activity_material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    activity_id BIGINT NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
                                    material_name VARCHAR(160) NOT NULL, quantity_description VARCHAR(160),
                                    is_required BOOLEAN NOT NULL DEFAULT TRUE, acquisition_type VARCHAR(30)
);
CREATE TABLE user_hobbies (
                              user_hobby_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                              hobby_id BIGINT NOT NULL REFERENCES hobbies(hobby_id),
                              tree_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK(tree_status IN ('ACTIVE','PAUSED','ENDED')),
    -- PAUSED and ENDED free a planting slot; completed stage-5 trees remain ACTIVE unless user pauses them.
                              current_stage_number SMALLINT NOT NULL DEFAULT 0 CHECK(current_stage_number BETWEEN 0 AND 5),
                              planted_at TIMESTAMPTZ NOT NULL DEFAULT now(), paused_at TIMESTAMPTZ, ended_at TIMESTAMPTZ,
                              UNIQUE(user_id,hobby_id)
);
CREATE TABLE activity_records (
                                  activity_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  user_hobby_id BIGINT NOT NULL REFERENCES user_hobbies(user_hobby_id) ON DELETE CASCADE,
                                  activity_id BIGINT NOT NULL REFERENCES activities(activity_id),
                                  activity_status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS' CHECK(activity_status IN ('IN_PROGRESS','COMPLETED','PARTIAL','NOT_DONE')),
                                  step_progress JSONB NOT NULL DEFAULT '{}'::jsonb,
                                  attempt_count INTEGER NOT NULL DEFAULT 1 CHECK(attempt_count > 0),
                                  growth_counted BOOLEAN NOT NULL DEFAULT FALSE,
                                  growth_stage_number SMALLINT CHECK(growth_stage_number BETWEEN 0 AND 5),
                                  started_at TIMESTAMPTZ, last_resumed_at TIMESTAMPTZ, finished_at TIMESTAMPTZ,
                                  satisfaction SMALLINT CHECK(satisfaction BETWEEN 1 AND 5),
                                  perceived_difficulty VARCHAR(20), actual_minutes INTEGER CHECK(actual_minutes >= 0),
                                  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                                  UNIQUE(user_hobby_id,activity_id),
                                  CHECK(growth_stage_number IS NULL OR growth_counted),
                                  CHECK(finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at),
                                  CHECK(NOT growth_counted OR (activity_status='COMPLETED' AND growth_stage_number IS NOT NULL))
);
CREATE TABLE recommendations (
                                 recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                 preference_snapshot JSONB NOT NULL, recommendation_version VARCHAR(80),
                                 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE recommendation_items (
                                      recommendation_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      recommendation_id BIGINT NOT NULL REFERENCES recommendations(recommendation_id) ON DELETE CASCADE,
                                      hobby_id BIGINT NOT NULL REFERENCES hobbies(hobby_id),
                                      first_activity_id BIGINT REFERENCES activities(activity_id) ON DELETE SET NULL,
                                      rank_order SMALLINT NOT NULL CHECK(rank_order > 0), score NUMERIC(5,2),
                                      recommendation_reason TEXT NOT NULL, selected_at TIMESTAMPTZ,
                                      UNIQUE(recommendation_id,rank_order), UNIQUE(recommendation_id,hobby_id)
);
CREATE TABLE user_notifications (
                                    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                    notification_type VARCHAR(40) NOT NULL, title VARCHAR(160) NOT NULL, message TEXT NOT NULL,
                                    related_user_hobby_id BIGINT REFERENCES user_hobbies(user_hobby_id) ON DELETE SET NULL,
                                    related_activity_id BIGINT REFERENCES activities(activity_id) ON DELETE SET NULL,
                                    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), read_at TIMESTAMPTZ
);
-- Four additional tables required by the v5 UI scope
CREATE TABLE saved_activities (
                                  user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                  activity_id BIGINT NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
                                  saved_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY(user_id,activity_id)
);
-- Simplified content: a row represents one bookable session/listing, not a separate venue/session master.
CREATE TABLE experiences (
                             experience_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             experience_type VARCHAR(20) NOT NULL CHECK(experience_type IN ('CLASS','MEETUP','EXTERNAL')),
                             linked_activity_id BIGINT REFERENCES activities(activity_id) ON DELETE SET NULL,
                             title VARCHAR(160) NOT NULL, description TEXT,
                             hobby_id BIGINT REFERENCES hobbies(hobby_id) ON DELETE SET NULL,
                             region_sido VARCHAR(50), region_sigungu VARCHAR(50), venue_name VARCHAR(160), venue_address TEXT,
                             provider_name VARCHAR(160), partner_label VARCHAR(30),
                             starts_at TIMESTAMPTZ, ends_at TIMESTAMPTZ, capacity INTEGER CHECK(capacity > 0),
                             price_amount INTEGER CHECK(price_amount >= 0), external_url TEXT,
                             booking_mode VARCHAR(20) NOT NULL DEFAULT 'EXTERNAL' CHECK (booking_mode IN ('EXTERNAL','INQUIRY','NONE')),
                             thumbnail_image_key TEXT,
                             listing_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK(listing_status IN ('DRAFT','OPEN','CLOSED','CANCELLED')),
                             created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                             CHECK(ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);
-- Reservation tracking only. External payment provider handles payment; no card data stored.
CREATE TABLE experience_reservations (
                                         reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         reservation_code VARCHAR(60) NOT NULL UNIQUE,
                                         experience_id BIGINT NOT NULL REFERENCES experiences(experience_id),
                                         user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                         reservation_status VARCHAR(24) NOT NULL DEFAULT 'REQUESTED' CHECK(reservation_status IN ('REQUESTED','CONFIRMED','CANCELLED','ATTENDED')),
                                         party_size SMALLINT NOT NULL DEFAULT 1 CHECK(party_size BETWEEN 1 AND 4),
                                         total_amount INTEGER CHECK(total_amount >= 0),
                                         payment_method_label VARCHAR(40), -- display-only; no card number/token stored
                                         external_booking_ref VARCHAR(160), attendance_verified_at TIMESTAMPTZ,
                                         credited_activity_record_id BIGINT UNIQUE REFERENCES activity_records(activity_record_id) ON DELETE SET NULL,
                                         booked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                                         updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), UNIQUE(experience_id,user_id),
                                         CHECK (attendance_verified_at IS NULL OR reservation_status='ATTENDED'),
                                         CHECK (credited_activity_record_id IS NULL OR attendance_verified_at IS NOT NULL)
);
CREATE TABLE notification_subscriptions (
                                            subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
                                            subscription_type VARCHAR(40) NOT NULL CHECK(subscription_type IN ('CLASS_OPEN','CHAT_LAUNCH')),
                                            experience_id BIGINT REFERENCES experiences(experience_id) ON DELETE CASCADE,
                                            subscribed_at TIMESTAMPTZ NOT NULL DEFAULT now(), unsubscribed_at TIMESTAMPTZ,
                                            CHECK ((subscription_type='CLASS_OPEN' AND experience_id IS NOT NULL) OR (subscription_type='CHAT_LAUNCH' AND experience_id IS NULL))
);
CREATE UNIQUE INDEX uq_sub_class ON notification_subscriptions(user_id,experience_id) WHERE subscription_type='CLASS_OPEN' AND unsubscribed_at IS NULL;
CREATE UNIQUE INDEX uq_sub_chat ON notification_subscriptions(user_id) WHERE subscription_type='CHAT_LAUNCH' AND unsubscribed_at IS NULL;
CREATE INDEX idx_consent_user_time ON location_consent_history(user_id,changed_at DESC);
CREATE INDEX idx_stage_hobby ON hobby_stages(hobby_id);
CREATE INDEX idx_activities_stage ON activities(hobby_stage_id);
CREATE INDEX idx_materials_activity ON activity_materials(activity_id);
CREATE INDEX idx_user_hobbies_user_status ON user_hobbies(user_id,tree_status);
CREATE INDEX idx_records_tree_status ON activity_records(user_hobby_id,activity_status);
CREATE INDEX idx_recommendations_user_time ON recommendations(user_id,created_at DESC);
CREATE INDEX idx_rec_items_hobby ON recommendation_items(hobby_id);
CREATE INDEX idx_notifications_user_time ON user_notifications(user_id,created_at DESC);
CREATE INDEX idx_experiences_linked_activity ON experiences(linked_activity_id);
CREATE INDEX idx_experiences_type_start ON experiences(experience_type,starts_at);
CREATE INDEX idx_reservations_user ON experience_reservations(user_id);
CREATE INDEX idx_reservations_capacity ON experience_reservations(experience_id,reservation_status);
-- Business rules enforced in Spring transactions (not guaranteed by this DDL):
-- (1) <=5 ACTIVE trees; PAUSED/ENDED release slot. Lock the user row before planting.
-- (2) activity belongs to same hobby as user_hobby; only current-stage distinct COMPLETED
--     activities can earn growth_counted=true, once per user_hobby/activity.
-- (3) Stage 0..4: three distinct credited completions advance one stage; stage 5 is terminal.
--     No automatic advance from stage 5. Historical activity completions remain readable.
-- (4) Existing activity_records row is a summary; repeated attempt event history is NOT stored.
-- (5) Reservation capacity = sum(party_size) for CONFIRMED and ATTENDED; lock experience row
--     and recheck before confirming. REQUESTED does not hold seats.
-- (6) Reservation ATTENDED only after external evidence; then grant linked activity credit
--     idempotently; credited_activity_record_id must belong to same user's tree and activity.
-- (7) External checkout only: no internal payment ledger, gateway callbacks, refund processing.
-- (8) profile_image_key stores private S3 key, not an expiring presigned URL.
-- (9) coordinates are never persisted; region only; consent logs retention needs legal review.
-- (10) updated_at needs JPA auditing or application-managed updates.
-- (11) class repeat sessions use separate experiences rows; availability is per row.
-- (12) advertisement metadata and AI coach messages are NOT persisted in v1.2.

