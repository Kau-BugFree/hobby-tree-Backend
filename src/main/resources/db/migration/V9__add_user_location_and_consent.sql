-- API-42 활동 지역 설정 / API-43 위치 동의. V1's user_locations/location_consent_history
-- (region_sido/region_sigungu strings, location_status, consent_action/terms_version) predate
-- API-41's regionId-hierarchy design and don't match what API.md actually needs - no service
-- code has ever read or written either table, so they're dropped and recreated rather than
-- altered.
DROP TABLE location_consent_history;
DROP TABLE user_locations;

CREATE TABLE user_locations (
    user_location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    region_id BIGINT NOT NULL REFERENCES regions(region_id),
    source VARCHAR(10) NOT NULL CHECK (source IN ('MANUAL', 'DEVICE')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Append-only: API-43 adds a row per consent decision rather than updating one in place, so the
-- "current" state is always the latest row per (user_id, consent_type).
CREATE TABLE location_consents (
    location_consent_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    consent_type VARCHAR(30) NOT NULL CHECK (consent_type IN ('NEARBY_EXPERIENCES')),
    version VARCHAR(40) NOT NULL,
    agreed BOOLEAN NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_location_consents_latest ON location_consents(user_id, consent_type, recorded_at DESC, location_consent_id DESC);
