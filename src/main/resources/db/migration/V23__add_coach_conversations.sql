-- API-34 Part 1 (하비 코치, AI 연동 제외): conversation/message persistence only, per the team's
-- 2026-11-03/04 decision that the chat must be multi-turn and server-persisted. The actual
-- RAG/Gemini answer is Part 2's job - until then every assistant message's answer_version is
-- 'PART1_PLACEHOLDER' and reference_items/suggested_activities stay the empty-array default.
CREATE TABLE coach_conversations (
    conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    user_hobby_id BIGINT REFERENCES user_hobbies(user_hobby_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_message_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Supports the "대화 이력 조회" list page: lastMessageAt DESC, id as the tiebreak.
CREATE INDEX idx_coach_conversations_user
    ON coach_conversations(user_id, last_message_at DESC, conversation_id DESC);

-- Postgres never auto-indexes a FK column; without this, the ON DELETE SET NULL triggered by
-- deleting a user_hobbies row would have to scan every coach_conversations row. Partial because
-- most conversations never set this column (userHobbyId is optional context).
CREATE INDEX idx_coach_conversations_user_hobby
    ON coach_conversations(user_hobby_id) WHERE user_hobby_id IS NOT NULL;

CREATE TABLE coach_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES coach_conversations(conversation_id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('USER','ASSISTANT')),
    content TEXT NOT NULL,
    answer_version VARCHAR(80),
    reference_items JSONB NOT NULL DEFAULT '[]'::jsonb,
    suggested_activities JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_coach_messages_conversation ON coach_messages(conversation_id, message_id);
