-- API-35 (클래스·모임 목록): region_sido/region_sigungu predates the regions table (API-41,
-- hobbytree-team-decisions-2026-11-04) - replace with a real FK so filtering/response can use
-- regionId like every other region-aware API.
ALTER TABLE experiences ADD COLUMN region_id BIGINT REFERENCES regions(region_id);

-- Backfill: match the legacy free-text sido/sigungu against regions (SIGUNGU level, matching
-- the sigungu name and whose parent sido's name or full_name starts with the legacy sido text
-- - handles short/full-name differences like "서울" vs "서울특별시"). A short sido prefix like
-- "대" matches both 대구 and 대전, so a sigungu name repeated across provinces (e.g. "중구") can
-- resolve to more than one candidate region - only set region_id when exactly one candidate
-- matches; an ambiguous or absent match is left for the legacy_region_label fallback below
-- rather than guessing one of several equally-plausible regions.
WITH candidates AS (
    SELECT e2.experience_id, r.region_id,
           COUNT(*) OVER (PARTITION BY e2.experience_id) AS match_count
    FROM experiences e2
    JOIN regions r ON r.level = 'SIGUNGU' AND r.name = e2.region_sigungu
    JOIN regions sido ON sido.region_id = r.parent_region_id
        AND (sido.name = e2.region_sido OR sido.full_name LIKE e2.region_sido || '%')
    WHERE e2.region_sigungu IS NOT NULL
)
UPDATE experiences e
SET region_id = candidates.region_id
FROM candidates
WHERE candidates.experience_id = e.experience_id AND candidates.match_count = 1;

-- Preserve anything that couldn't be auto-mapped (differently formatted legacy text, or a
-- sigungu name absent from the regions seed) instead of silently dropping it once
-- region_sido/region_sigungu go away below.
-- 101, not 100: region_sido/region_sigungu are each VARCHAR(50), so a maxed-out pair
-- concatenated with a space is 101 characters.
ALTER TABLE experiences ADD COLUMN legacy_region_label VARCHAR(101);

UPDATE experiences
SET legacy_region_label = TRIM(CONCAT_WS(' ', region_sido, region_sigungu))
WHERE region_id IS NULL AND (region_sido IS NOT NULL OR region_sigungu IS NOT NULL);

ALTER TABLE experiences
    DROP COLUMN region_sido,
    DROP COLUMN region_sigungu;

-- API.md documents experience_providers as a proposed table ("신규 제안") - no real
-- partner/provider integration exists or is planned for MVP (team decision: Naver API surfaces
-- a small admin-curated set of businesses instead), so this is just a name lookup, not a
-- provider account/ownership system.
CREATE TABLE experience_providers (
    provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL
);

ALTER TABLE experiences ADD COLUMN provider_id BIGINT REFERENCES experience_providers(provider_id);

-- Backfill: create a provider row for each distinct legacy provider_name and link existing
-- experiences to it before that column goes away, so a row that already listed a provider
-- doesn't silently show provider=null afterward.
INSERT INTO experience_providers (name)
SELECT DISTINCT provider_name FROM experiences WHERE provider_name IS NOT NULL;

UPDATE experiences e
SET provider_id = p.provider_id
FROM experience_providers p
WHERE p.name = e.provider_name AND e.provider_name IS NOT NULL;

-- provider_name (now backfilled into experience_providers.name, looked up through the FK
-- above) is no longer needed.
ALTER TABLE experiences DROP COLUMN provider_name;

-- A class/모임 can recur across multiple scheduled occurrences; API-35's list sorts/shows the
-- soonest upcoming one per experience ("다음 일정"), so scheduling moves out of the
-- single-occurrence starts_at/ends_at columns below (dropped) into its own table.
CREATE TABLE experience_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experience_id BIGINT NOT NULL REFERENCES experiences(experience_id) ON DELETE CASCADE,
    starts_at TIMESTAMPTZ NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0)
);

CREATE INDEX idx_experience_sessions_experience_starts_at
    ON experience_sessions(experience_id, starts_at);

-- Backfill existing rows' single occurrence into the new table before dropping the columns
-- it came from, so that data isn't silently lost for any environment with existing rows.
-- ends_at IS NULL means the old row never recorded a duration, so this defaults to 60 minutes
-- (duration_minutes is NOT NULL and must be > 0) rather than guessing; starts_at IS NULL rows
-- have nothing to migrate and are simply left without a session (nextSession stays null for
-- them going forward, same as before this migration). A real gap under a minute (e.g.
-- ends_at just 1 second after starts_at) rounds to 0, which the NOT NULL/>0 constraint would
-- reject outright and abort this migration - GREATEST(...,1) floors it at 1 minute instead,
-- without disturbing the ends_at IS NULL -> 60 default.
INSERT INTO experience_sessions (experience_id, starts_at, duration_minutes)
SELECT experience_id,
       starts_at,
       CASE
         WHEN ends_at IS NULL THEN 60
         ELSE GREATEST(ROUND(EXTRACT(EPOCH FROM (ends_at - starts_at)) / 60)::int, 1)
       END
FROM experiences
WHERE starts_at IS NOT NULL;

ALTER TABLE experiences DROP CONSTRAINT experiences_check;
ALTER TABLE experiences DROP COLUMN starts_at, DROP COLUMN ends_at;
