-- API-35 (클래스·모임 목록): region_sido/region_sigungu predates the regions table (API-41,
-- hobbytree-team-decisions-2026-11-04) - replace with a real FK so filtering/response can use
-- regionId like every other region-aware API.
ALTER TABLE experiences
    DROP COLUMN region_sido,
    DROP COLUMN region_sigungu,
    ADD COLUMN region_id BIGINT REFERENCES regions(region_id);

-- API.md documents experience_providers as a proposed table ("신규 제안") - no real
-- partner/provider integration exists or is planned for MVP (team decision: Naver API surfaces
-- a small admin-curated set of businesses instead), so this is just a name lookup, not a
-- provider account/ownership system.
CREATE TABLE experience_providers (
    provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL
);

-- provider_name (a free-text column with no relation to the new table) is superseded by
-- experience_providers.name, looked up through this FK.
ALTER TABLE experiences
    DROP COLUMN provider_name,
    ADD COLUMN provider_id BIGINT REFERENCES experience_providers(provider_id);

-- A class/모임 can recur across multiple scheduled occurrences; API-35's list sorts/shows the
-- soonest upcoming one per experience ("다음 일정"), so scheduling moves out of the
-- single-occurrence starts_at/ends_at columns below (dropped) into its own table.
CREATE TABLE experience_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experience_id BIGINT NOT NULL REFERENCES experiences(experience_id) ON DELETE CASCADE,
    starts_at TIMESTAMPTZ NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0)
);

CREATE INDEX idx_experience_sessions_experience_starts_at
    ON experience_sessions(experience_id, starts_at);

-- Backfill existing rows' single occurrence into the new table before dropping the columns
-- it came from, so that data isn't silently lost for any environment with existing rows.
-- ends_at IS NULL means the old row never recorded a duration, so this defaults to 60 minutes
-- (duration_minutes is NOT NULL and must be > 0) rather than guessing; starts_at IS NULL rows
-- have nothing to migrate and are simply left without a session (nextSession stays null for
-- them going forward, same as before this migration).
INSERT INTO experience_sessions (experience_id, starts_at, duration_minutes)
SELECT experience_id,
       starts_at,
       COALESCE(ROUND(EXTRACT(EPOCH FROM (ends_at - starts_at)) / 60)::int, 60)
FROM experiences
WHERE starts_at IS NOT NULL;

ALTER TABLE experiences DROP CONSTRAINT experiences_check;
ALTER TABLE experiences DROP COLUMN starts_at, DROP COLUMN ends_at;
