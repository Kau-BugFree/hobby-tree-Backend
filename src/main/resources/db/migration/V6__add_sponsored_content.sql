-- API-49 활동 관련 제휴 콘텐츠 조회. No real sponsor deal exists yet (Coupang Partners
-- approval pending), so this ships with the schema only; rows are seeded manually/by tests
-- until a real affiliate feed replaces the placeholder data.
CREATE TABLE sponsored_contents (
    sponsored_content_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    description VARCHAR(500),
    sponsor_name VARCHAR(160) NOT NULL,
    thumbnail_url TEXT,
    content_type VARCHAR(20) NOT NULL CHECK (content_type IN ('PRODUCT','CLASS','ARTICLE')),
    disclosure_label VARCHAR(30) NOT NULL DEFAULT '광고·제휴',
    -- externalUrl must be a server-curated allowed HTTPS address, never user input. The
    -- scheme alone ('https://' with LIKE 'https://%') would also match a host-less URL
    -- like 'https://' or 'https:///path'; require at least one non-slash character right
    -- after the scheme so a real host is present.
    external_url TEXT NOT NULL CHECK (external_url ~ '^https://[^/]'),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);

CREATE TABLE activity_sponsored_contents (
    activity_id BIGINT NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
    sponsored_content_id BIGINT NOT NULL REFERENCES sponsored_contents(sponsored_content_id) ON DELETE CASCADE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (activity_id, sponsored_content_id)
);

CREATE INDEX idx_activity_sponsored_sort ON activity_sponsored_contents(activity_id, sort_order);
