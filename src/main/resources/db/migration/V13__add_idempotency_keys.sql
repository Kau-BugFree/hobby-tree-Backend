-- Generic idempotency support, first used by API-14's POST /recommendations. Scoped by
-- endpoint (not just user+key) so the same key value reused across different APIs later can't
-- collide.
CREATE TABLE idempotency_keys (
    idempotency_key_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    endpoint VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    -- INTEGER, not SMALLINT: IdempotencyKey.responseStatus is a Java Integer, and Hibernate's
    -- schema validation (ddl-auto=validate) rejects a column type narrower than the mapped
    -- Java type at startup.
    response_status INTEGER,
    response_body JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (status IN ('PENDING', 'COMPLETED')),
    CHECK ((status = 'COMPLETED') = (response_status IS NOT NULL AND response_body IS NOT NULL)),
    UNIQUE (user_id, endpoint, idempotency_key)
);
