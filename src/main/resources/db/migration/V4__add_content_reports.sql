-- API-48 활동·콘텐츠 문제 신고. Polymorphic target (ACTIVITY | SPONSORED_CONTENT) by
-- design: sponsored_contents does not exist yet (API-49 unbuilt), so target_id has no
-- DB-level FK and existence/access is validated in the service layer per target_type.
CREATE TABLE content_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    target_type VARCHAR(20) NOT NULL CHECK (target_type IN ('ACTIVITY','SPONSORED_CONTENT')),
    target_id BIGINT NOT NULL,
    reason VARCHAR(30) NOT NULL CHECK (reason IN ('WRONG_INFORMATION','BROKEN_LINK','INAPPROPRIATE','OTHER')),
    description VARCHAR(1000) NOT NULL CHECK (length(btrim(description)) BETWEEN 10 AND 1000),
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED' CHECK (status IN ('RECEIVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Supports the service-layer 24h duplicate check (same reporter/target/reason).
CREATE INDEX idx_reports_dedupe ON content_reports(reporter_user_id, target_type, target_id, reason, created_at DESC);
