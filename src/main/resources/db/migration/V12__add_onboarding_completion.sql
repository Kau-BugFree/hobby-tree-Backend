-- Append-only agreement history, one row per decision - same design as location_consents
-- (API-43). terms_id references OnboardingService.TERMS's static list, not a DB table (API-10
-- keeps terms as a Java constant, not a terms table), so no FK here.
CREATE TABLE user_terms_agreements (
    user_terms_agreement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    terms_id INT NOT NULL,
    version VARCHAR(40) NOT NULL,
    agreed BOOLEAN NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_user_terms_agreements_user ON user_terms_agreements(user_id, terms_id, recorded_at DESC);
